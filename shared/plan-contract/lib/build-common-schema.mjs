#!/usr/bin/env node
// build-common-schema.mjs — regenerates schema/common.schema.json from the
// single-source business-types registry (../business-types.md).
//
// The `businessType` enum is every slug in the registry table; `sipocInputType`
// is that set minus the ambiguous / non-atomic types that must never be a SIPOC
// input (they hide composite or free-form payloads, e.g. metadata, snippet).
// Run this whenever business-types.md changes:  node lib/build-common-schema.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const registryPath = path.join(here, '..', 'business-types.md');
const outPath = path.join(here, '..', 'schema', 'common.schema.json');

// Slugs ambiguous or non-atomic as a SIPOC input: composites, free-form blobs,
// files, secrets and geo shapes. Keeping them out forces inputs to be a single
// unambiguous scalar the Action can validate.
const AMBIGUOUS_FOR_SIPOC = new Set([
  'metadata', 'snippet', 'multiOptions', 'geofence', 'route', 'area', 'location',
  'place', 'bpmn', 'dbml', 'post', 'hash', 'token', 'password', 'file', 'image',
  'video', 'audio', 'pdf', 'path',
]);

function extractSlugs(md) {
  // The registry is the first table; stop at the "### Relationships" heading so
  // belongs_to/has_one/has_many (UI-intent only) never count as column types.
  const registry = md.split(/^###\s+Relationships/m)[0];
  const slugs = [];
  for (const m of registry.matchAll(/^\|\s*`([a-zA-Z][a-zA-Z0-9]*)`\s*\|/gm)) {
    slugs.push(m[1]);
  }
  return [...new Set(slugs)].sort();
}

const md = fs.readFileSync(registryPath, 'utf8');
const businessTypes = extractSlugs(md);
if (businessTypes.length < 20) {
  console.error(`build-common-schema: only ${businessTypes.length} slugs parsed from the registry — aborting (expected 40+).`);
  process.exit(1);
}
const sipocInputTypes = businessTypes.filter((s) => !AMBIGUOUS_FOR_SIPOC.has(s));

// A predicate is `true`, `false`, or 1+ `field op value` comparisons joined by
// and/or. The validator resolves field/enum names against the entity; the schema
// only guarantees the shape so a free-form sentence can never slip through.
const COMPARISON = "[a-z_][a-z0-9_.]*\\s*(=|!=|>=|<=|>|<)\\s*\\S+";
const predicatePattern = `^(true|false|${COMPARISON}(\\s+(and|or)\\s+${COMPARISON})*)$`;

const schema = {
  $id: 'https://opscale.co/plan-contract/common.schema.json',
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  title: 'Opscale Plan-contract — shared definitions',
  description: 'Generated by lib/build-common-schema.mjs from business-types.md. Do not edit by hand.',
  $defs: {
    subprocessCode: { type: 'string', pattern: '^SP-\\d{2}$' },
    stepCode: { type: 'string', pattern: '^SP-\\d{2}-\\d{2}$' },
    opCode: { type: 'string', pattern: '^SP-\\d{2}-\\d{2}-[CL]\\d{2}$' },
    composedOpCode: { type: 'string', pattern: '^SP-\\d{2}-\\d{2}-[CL]\\d{2}-[CLO]\\d{2}$' },
    entitySlug: { type: 'string', pattern: '^[a-z][a-z0-9-]*$' },
    logicId: {
      type: 'string',
      pattern: '^[a-z]+(-[a-z]+){1,2}$',
      description: 'verb + noun, 2 words (3 only when the noun is compound)',
    },
    ruleCode: { type: 'string', pattern: '^BR-\\d{2}$' },
    businessType: { type: 'string', enum: businessTypes },
    sipocInputType: { type: 'string', enum: sipocInputTypes },
    predicate: { type: 'string', pattern: predicatePattern },
    module: {
      type: 'object',
      additionalProperties: false,
      required: ['software', 'domain', 'subdomain'],
      properties: {
        software: { type: 'string', minLength: 1 },
        domain: { type: 'string', minLength: 1 },
        subdomain: { type: 'string', minLength: 1 },
      },
    },
  },
};

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, JSON.stringify(schema, null, 2) + '\n');
console.log(`common.schema.json written: ${businessTypes.length} business types, ${sipocInputTypes.length} sipoc-input types.`);
